// Writes the color tokens for both themes from the validated palette, and refuses to build when the
// data the pages read is missing. Dark is the default: a flight deck at night. Light is a true theme
// on neutral paper, chosen by the reader, and print always takes it.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const needed = ["site.json", "scorecard.json", "turns.json", "catalog.json", "connect.json", "playbook.json", "briefing.json",
  "recorded_session.json", "manifest_index.parquet", "traces/floor.parquet"];
const missing = needed.filter((f) => !existsSync(join(root, "public", "data", f)));
if (missing.length) throw new Error(`public/data is missing ${missing.join(", ")}: run scripts/export_site.py from the repository root`);

const palette = JSON.parse(readFileSync(join(root, "src", "theme", "palette.json"), "utf8"));
const ROLES = ["warehouse", "model", "person", "gemini", "groq", "openrouter", "sambanova", "ollama"];
const block = (mode, indent, important = false) => {
  const p = palette[mode];
  const lines = [
    `--surface: ${p.surface};`,
    `--raised: ${p.raised};`,
    `--hairline: ${p.hairline};`,
    `--ink: ${p.ink};`,
    `--ink2: ${p.ink2};`,
    `--control: ${p.control};`,
    ...p.categorical.map((c, i) => `--${ROLES[i]}: ${c};`),
    ...p.sequential.map((c, i) => `--seq-${i + 1}: ${c};`),
    ...p.diverging.map((c, i) => `--div-${i + 1}: ${c};`),
    ...Object.entries(p.status).map(([k, c]) => `--${k}: ${c};`),
    `color-scheme: ${mode};`,
  ];
  return lines.map((l) => `${indent}${important ? l.replace(/;$/, " !important;") : l}`).join("\n");
};
writeFileSync(
  join(root, "src", "app", "tokens.css"),
  `/* Generated by scripts/prepare-assets.mjs from src/theme/palette.json. Do not edit. */\n` +
    `:root {\n${block("dark", "  ")}\n}\n\n` +
    `:root[data-theme="light"] {\n${block("light", "  ")}\n}\n\n` +
    `@media print {\n  :root {\n${block("light", "    ", true)}\n  }\n}\n`,
);
console.log("prepared: the color tokens (dark first) and a check of public/data");
